function initCustomCursor() {
  const canUseCustomCursor = window.matchMedia("(hover: hover) and (pointer: fine)").matches;

  if (!canUseCustomCursor) return;

  const cursor = document.createElement("div");
  cursor.className = "custom-cursor";
  document.body.appendChild(cursor);
  document.body.classList.add("custom-cursor-enabled");
  document.body.classList.add("cursor-spotlight-enabled");

  const interactiveSelector = [
    "a",
    "button",
    "summary",
    "[role='button']",
    "[data-view]",
    "[data-calendar-date]",
    "[data-calendar-menu]",
    "[data-calendar-year]",
    "[data-calendar-info-toggle]",
    "[data-calendar-months-toggle]",
    "[data-media-menu]",
    "[data-media-type]",
    "[data-archive-menu]",
    "[data-archive-type]",
    "[data-archive-year-menu]",
    "[data-archive-year]",
    "[data-archive-clear]",
    "[data-archive-entry]",
    "[data-moment-menu]",
    "[data-moment-view]",
    "[data-moment-photo]",
    "[data-note-key]",
    "[data-why-question-next]",
    "[data-theme-toggle]",
    ".media-card",
    ".moment-photo",
    ".album-photo",
  ].join(", ");
  const nativeCursorSelector = [
    "input",
    "textarea",
    "select",
    "[contenteditable='true']",
    ".media-note-modal",
    ".moment-lightbox",
  ].join(", ");

  let cursorX = 0;
  let cursorY = 0;
  let cursorVisible = false;
  let cursorActive = false;
  let cursorPressed = false;
  let cursorSpotlightReady = false;
  let cursorFrame = null;

  const renderCursor = () => {
    cursorFrame = null;
    cursor.style.left = `${cursorX}px`;
    cursor.style.top = `${cursorY}px`;
    document.documentElement.style.setProperty("--cursor-x", cursorVisible ? `${cursorX}px` : "-999px");
    document.documentElement.style.setProperty("--cursor-y", cursorVisible ? `${cursorY}px` : "-999px");
    cursor.classList.toggle("is-visible", cursorVisible);
    cursor.classList.toggle("is-active", cursorActive);
    cursor.classList.toggle("is-pressed", cursorPressed);
    if (cursorSpotlightReady) {
      document.body.classList.add("cursor-spotlight-visible");
    }
  };

  const scheduleCursorRender = () => {
    if (cursorFrame !== null) return;
    cursorFrame = window.requestAnimationFrame(renderCursor);
  };

  const hideCursor = () => {
    cursorVisible = false;
    cursorActive = false;
    cursorPressed = false;
    scheduleCursorRender();
  };

  document.addEventListener("mousemove", (event) => {
    if (event.target.closest(nativeCursorSelector)) {
      hideCursor();
      return;
    }

    cursorX = event.clientX;
    cursorY = event.clientY;
    cursorVisible = true;
    cursorSpotlightReady = true;
    cursorActive = Boolean(event.target.closest(interactiveSelector));
    scheduleCursorRender();
  });

  document.addEventListener("mouseleave", hideCursor);

  document.addEventListener("mousedown", () => {
    if (!cursorVisible) return;
    cursorPressed = true;
    scheduleCursorRender();
  });

  document.addEventListener("mouseup", () => {
    cursorPressed = false;
    scheduleCursorRender();
  });

  window.addEventListener("blur", hideCursor);
  document.addEventListener("visibilitychange", () => {
    if (document.hidden) hideCursor();
  });
}

function initColorMode() {
  const systemTheme = window.matchMedia("(prefers-color-scheme: dark)");
  let userTheme = null;

  try {
    userTheme = localStorage.getItem("theme");
  } catch {
    userTheme = null;
  }

  const getPreferredTheme = () => userTheme || (systemTheme.matches ? "dark" : "light");
  let themeChangeToken = 0;

  const resetAnimatedTitle = () => {
    document.querySelectorAll(".brand-title-char").forEach((char) => {
      char.style.setProperty("--letter-y", "0px");
      char.style.setProperty("--letter-scale", "1");
      char.style.setProperty("--letter-rotate", "0deg");
    });
  };

  const applyTheme = (theme, options = {}) => {
    if (options.animate === false) {
      document.documentElement.dataset.theme = theme;
    } else {
      const token = ++themeChangeToken;
      resetAnimatedTitle();
      document.documentElement.classList.add("theme-changing");
      document.documentElement.dataset.theme = theme;
      window.requestAnimationFrame(() => {
        window.requestAnimationFrame(() => {
          if (token === themeChangeToken) {
            document.documentElement.classList.remove("theme-changing");
          }
        });
      });
    }
    const isDark = theme === "dark";
    const label = isDark ? "切换到日间模式" : "切换到夜间模式";
    colorModeToggle?.setAttribute("aria-label", label);
    colorModeToggle?.setAttribute("title", label);
  };

  applyTheme(getPreferredTheme(), { animate: false });

  colorModeToggle?.addEventListener("click", () => {
    const nextTheme = document.documentElement.dataset.theme === "dark" ? "light" : "dark";
    userTheme = nextTheme;
    try {
      localStorage.setItem("theme", nextTheme);
    } catch {
      // Theme can still work for this session if storage is unavailable.
    }
    applyTheme(nextTheme);
  });

  systemTheme.addEventListener("change", () => {
    if (!userTheme) applyTheme(getPreferredTheme());
  });
}

function initAnimatedTitle() {
  const title = document.querySelector("[data-animated-title]");
  const canAnimate = window.matchMedia("(pointer: fine)").matches &&
    !window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  if (!title || !canAnimate) return;

  const text = title.textContent.trim();
  title.setAttribute("aria-label", text);
  title.innerHTML = [...text]
    .map((char) => `<span class="brand-title-char" aria-hidden="true">${char}</span>`)
    .join("");

  const chars = [...title.querySelectorAll(".brand-title-char")];
  const resetChars = () => {
    chars.forEach((char) => {
      char.style.setProperty("--letter-y", "0px");
      char.style.setProperty("--letter-scale", "1");
      char.style.setProperty("--letter-rotate", "0deg");
    });
  };

  title.addEventListener("mousemove", (event) => {
    chars.forEach((char, index) => {
      const rect = char.getBoundingClientRect();
      const centerX = rect.left + rect.width / 2;
      const centerY = rect.top + rect.height / 2;
      const distance = Math.hypot(event.clientX - centerX, event.clientY - centerY);
      const influence = Math.max(0, 1 - distance / 74);
      const direction = event.clientX < centerX ? 1 : -1;
      const wave = Math.sin(index * 0.9 + influence * Math.PI);
      const y = -10 * influence;
      const scale = 1 + 0.13 * influence;
      const rotate = direction * (3.5 * influence + wave * 0.8 * influence);

      char.style.setProperty("--letter-y", `${y.toFixed(2)}px`);
      char.style.setProperty("--letter-scale", scale.toFixed(3));
      char.style.setProperty("--letter-rotate", `${rotate.toFixed(2)}deg`);
    });
  });

  title.addEventListener("mouseleave", resetChars);
  title.addEventListener("blur", resetChars, true);
}

