function renderSidebarForView(view = activeView) {
  const modules = sidebarModulesByPage[normalizeView(view)] || [];
  const isCenteredSidebar = centeredSidebarViews.has(normalizeView(view));

  sidebarPanels.forEach((panel) => {
    const moduleIndex = modules.indexOf(panel.dataset.sidebarModule);
    panel.hidden = moduleIndex < 0;
    panel.style.order = moduleIndex >= 0 ? String(moduleIndex + 1) : "";
  });

  if (rightPanel) {
    rightPanel.dataset.sidebarPage = normalizeView(view);
    rightPanel.dataset.sidebarLayout = isCenteredSidebar ? "center" : "default";
  }
  if (siteShell) {
    siteShell.dataset.sidebarPage = normalizeView(view);
    siteShell.dataset.sidebarLayout = isCenteredSidebar ? "center" : "default";
  }
  if (asideToggle) {
    asideToggle.dataset.sidebarPage = normalizeView(view);
    asideToggle.dataset.sidebarLayout = isCenteredSidebar ? "center" : "default";
  }
}

function applyAsideState() {
  const canUseAside = canToggleAside();
  const isClosed = canUseAside && asideState === "closed";
  const label = isClosed ? "显示右侧栏" : "隐藏右侧栏";

  siteShell.classList.toggle("aside-capable", canUseAside);
  siteShell.classList.toggle("aside-closed", isClosed);

  if (asideToggle) {
    asideToggle.hidden = !canUseAside;
    asideToggle.setAttribute("aria-label", label);
    asideToggle.setAttribute("title", label);
    asideToggle.setAttribute("aria-pressed", String(isClosed));
  }
}

function setActiveView(view) {
  const previousView = activeView;
  const nextView = normalizeView(view);
  const isViewSwitching = previousView !== nextView;
  if (isViewSwitching) {
    siteShell.classList.add("is-view-switching");
  }
  topNav?.classList.remove("is-hidden");
  activeView = nextView;
  if (previousView !== "moments" && activeView === "moments" && !activeMomentStatusItem) {
    activeMomentStatusItem = getMomentStatusLibrary()[0] || null;
    renderMomentSidePanel();
  }
  if (activeView !== "articles") {
    activeArticleId = "";
    siteShell.classList.remove("article-reading");
  }
  viewPanels.forEach((panel) => {
    panel.hidden = panel.dataset.viewPanel !== activeView;
  });
  viewLinks.forEach((link) => {
    link.classList.toggle("active", link.dataset.view === activeView);
  });
  renderSidebarForView(activeView);
  siteShell.classList.toggle("media-mode", activeView === "media");
  siteShell.classList.toggle("moments-mode", activeView === "moments");
  siteShell.classList.toggle("calendar-mode", activeView === "calendar");
  siteShell.classList.toggle("archive-mode", activeView === "archive");
  applyAsideState();
  if (isViewSwitching) {
    window.requestAnimationFrame(() => {
      window.requestAnimationFrame(() => {
        siteShell.classList.remove("is-view-switching");
      });
    });
  }
}

function getInitialView() {
  const canonicalPath = window.location.pathname.replace(/\/about\/?$/, "/");
  if (canonicalPath !== window.location.pathname) {
    window.history.replaceState(null, "", `${canonicalPath}${window.location.search}`);
    return "about";
  }
  const hashView = window.location.hash.replace("#", "");
  if (hashView === "home") {
    window.history.replaceState(null, "", `${window.location.pathname}${window.location.search}`);
    return "calendar";
  }
  const hasPanel = [...viewPanels].some((panel) => panel.dataset.viewPanel === hashView);
  return hasPanel ? hashView : activeView;
}

function setMobileMenu(open) {
  window.clearTimeout(mobileMenuCloseTimer);
  navPinnedOpen = open;
  mobileMenuToggle?.setAttribute("aria-expanded", String(open));
  if (mobileMenu) {
    if (open) {
      mobileMenu.hidden = false;
      requestAnimationFrame(() => {
        mobileMenu.classList.add("is-open");
      });
    } else {
      mobileMenu.classList.remove("is-open");
      mobileMenuCloseTimer = window.setTimeout(() => {
        if (!navPinnedOpen) mobileMenu.hidden = true;
      }, 220);
    }
  }
  topNav?.classList.remove("is-hidden");
}

function jumpCalendarToTodayInstant() {
  const today = getBeijingToday();
  const todayKey = formatCalendarDate(today.getFullYear(), today.getMonth() + 1, today.getDate());
  activeCalendarYear = today.getFullYear();
  activeCalendarDate = todayKey;
  calendarPastMonthsOpen = true;
  renderCalendarYears();
  renderYearCalendar();
  setActiveView("calendar");
  setViewHash("calendar");
  window.requestAnimationFrame(() => {
    scrollActiveCalendarYearIntoView();
    const todayButton = yearCalendar?.querySelector(`[data-calendar-date="${todayKey}"]`);
    const monthSection = todayButton?.closest(".calendar-month");
    monthSection?.scrollIntoView({ block: "start", inline: "nearest", behavior: "auto" });
    todayButton?.closest(".calendar-days")?.scrollTo({
      left: Math.max(0, todayButton.offsetLeft - 16),
      behavior: "auto",
    });
  });
}

