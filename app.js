function renderHeatmap() {
  const heatmap = document.querySelector("#heatmap");
  const year = 2026;
  const formatKey = (date) =>
    `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
  const recordMap = new Map();
  const addRecord = (date, type) => {
    const current = recordMap.get(date) || {};
    current[type] = (current[type] || 0) + 1;
    recordMap.set(date, current);
  };

  posts.forEach((post) => addRecord(post.date, "文章"));
  mediaLogs.forEach((group) => {
    const [recordYear, recordMonth] = group.month.split(".");
    group.items.forEach((item, index) => {
      addRecord(`${recordYear}-${recordMonth}-${String(index + 1).padStart(2, "0")}`, item.type);
    });
  });
  heatmapSupplementRecords.forEach((record) => addRecord(record.date, record.type));

  const visibleMonths = [4, 5, 6].map((month) => new Date(year, month, 1));
  const renderDay = (date) => {
    const key = formatKey(date);
    const records = recordMap.get(key) || {};
    const count = Object.values(records).reduce((sum, value) => sum + value, 0);
    const level = count === 0 ? 0 : Math.min(3, count);
    const detail = Object.entries(records)
      .map(([type, value]) => `${type}${value}`)
      .join(" / ");
    const label = formatDate(formatKey(date));
    return `<button class="heatmap-cell ${count ? "has-record" : ""} level-${level}" type="button" title="${label}" aria-label="${label}" data-date="${key}" data-count="${count}"></button>`;
  };

  const monthBlocks = visibleMonths.map((monthDate) => {
    const month = monthDate.getMonth();
    const firstDay = new Date(year, month, 1);
    const lastDay = new Date(year, month + 1, 0);
    const leadingDays = (firstDay.getDay() + 6) % 7;
    const days = [];
    for (let date = new Date(firstDay); date <= lastDay; date.setDate(date.getDate() + 1)) {
      days.push(new Date(date));
    }
    const blanks = Array.from(
      { length: leadingDays },
      () => `<span class="heatmap-cell is-empty" aria-hidden="true"></span>`,
    );
    return `
      <div class="heatmap-month-block">
        <span class="heatmap-month-label">${month + 1}月</span>
        <div class="heatmap-cells">${blanks.join("")}${days.map(renderDay).join("")}</div>
      </div>
    `;
  });
  const recentRecordDays = [...recordMap.keys()].filter((date) => {
    const month = Number(date.slice(5, 7));
    return month >= 5 && month <= 7;
  }).length;

  heatmap.innerHTML = `
    <div class="heatmap-quarter">${monthBlocks.join("")}</div>
    <div class="heatmap-summary">
      <p>最近三个月，有 ${recentRecordDays} 天留下过记录。</p>
    </div>
  `;
}

