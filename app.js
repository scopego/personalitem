const dateKeyFormatter = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Asia/Shanghai",
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
});

const solarTermCache = new Map();

function formatDateKeyFromDate(date) {
  const values = Object.fromEntries(dateKeyFormatter.formatToParts(date).map((part) => [part.type, part.value]));
  return `${values.year}-${values.month}-${values.day}`;
}

function getDateFromKey(dateKey) {
  return new Date(`${dateKey}T00:00:00+08:00`);
}

function addDaysToDateKey(dateKey, days) {
  const date = getDateFromKey(dateKey);
  date.setUTCDate(date.getUTCDate() + days);
  return formatDateKeyFromDate(date);
}

function getLunarDateInfo(dateKey) {
  try {
    const parts = Object.fromEntries(
      lunarFormatter.formatToParts(getDateFromKey(dateKey)).map((part) => [part.type, part.value]),
    );
    const lunarDay = Number(parts.day);
    const lunarMonth = parts.month || "";
    const dayName = lunarDayNames[lunarDay] || "";
    const monthName = lunarMonth.replace(/^闰/, "");

    if (!lunarMonth || !dayName) return null;

    return {
      month: lunarMonth,
      monthName,
      day: lunarDay,
      dayName,
      displayName: lunarDay === 1 ? monthName.slice(0, 2) : dayName,
      fullName: `农历${lunarMonth}${dayName}`,
      isLeapMonth: lunarMonth.startsWith("闰"),
      relatedYear: parts.relatedYear || "",
      yearName: parts.yearName || "",
    };
  } catch {
    return null;
  }
}

function getFixedSolarFestivals(dateKey) {
  const name = fixedSolarFestivals[dateKey.slice(5)];
  return name ? [{ name, type: "fixed-festival" }] : [];
}

function getGeneratedLunarFestivals(dateKey) {
  const lunar = getLunarDateInfo(dateKey);
  if (!lunar || lunar.isLeapMonth) return [];

  const festivals = lunarFestivalRules
    .filter((rule) => rule.month === lunar.monthName && rule.day === lunar.day)
    .map((rule) => ({
      name: rule.name,
      type: "lunar-festival",
      lunar: lunar.fullName,
    }));

  const nextLunar = getLunarDateInfo(addDaysToDateKey(dateKey, 1));
  if (nextLunar && nextLunar.monthName === "正月" && nextLunar.day === 1 && !nextLunar.isLeapMonth) {
    festivals.push({
      name: "除夕",
      type: "lunar-festival",
      lunar: lunar.fullName,
    });
  }

  return festivals;
}

function getGeneratedSolarTermFestivals(dateKey) {
  const solarTerm = getGeneratedSolarTerm(dateKey);
  return solarTerm?.name === "清明" ? [{ name: "清明", type: "fixed-festival" }] : [];
}

function getOfficialHolidayFestivals(dateKey) {
  const arrangement = officialHolidayArrangements[Number(dateKey.slice(0, 4))];
  if (!arrangement) return [];

  const festivals = [];
  const dayOffName = arrangement.dayOff?.[dateKey];
  const adjustedName = arrangement.adjustedWorkdays?.[dateKey];

  if (dayOffName) {
    festivals.push({
      name: dayOffName,
      type: "public-holiday",
      isDayOff: true,
      source: arrangement.source,
    });
  }

  if (adjustedName) {
    festivals.push({
      name: adjustedName,
      type: "adjusted-workday",
      isAdjustedWorkday: true,
      source: arrangement.source,
    });
  }

  return festivals;
}

function normalizeAngle(angle) {
  return ((angle % 360) + 360) % 360;
}

function getSignedAngleDistance(angle, target) {
  return ((normalizeAngle(angle - target) + 540) % 360) - 180;
}

function getJulianDate(timestamp) {
  return timestamp / 86400000 + 2440587.5;
}

function getSolarLongitude(timestamp) {
  const daysSinceJ2000 = getJulianDate(timestamp) - 2451545.0;
  const meanLongitude = normalizeAngle(280.46646 + 0.98564736 * daysSinceJ2000);
  const meanAnomaly = normalizeAngle(357.52911 + 0.98560028 * daysSinceJ2000) * (Math.PI / 180);
  const center =
    1.914602 * Math.sin(meanAnomaly) +
    0.019993 * Math.sin(2 * meanAnomaly) +
    0.000289 * Math.sin(3 * meanAnomaly);
  return normalizeAngle(meanLongitude + center);
}

function findSolarTermDateKey(year, term) {
  let start = Date.UTC(year, term.month - 1, term.day - 8, 0);
  let end = Date.UTC(year, term.month - 1, term.day + 8, 0);

  if (getSignedAngleDistance(getSolarLongitude(start), term.longitude) > 0) return "";
  if (getSignedAngleDistance(getSolarLongitude(end), term.longitude) < 0) return "";

  for (let index = 0; index < 44; index += 1) {
    const middle = start + (end - start) / 2;
    if (getSignedAngleDistance(getSolarLongitude(middle), term.longitude) < 0) {
      start = middle;
    } else {
      end = middle;
    }
  }

  return formatDateKeyFromDate(new Date(start + (end - start) / 2));
}

function getSolarTermMap(year) {
  if (solarTermCache.has(year)) return solarTermCache.get(year);

  const terms = new Map();
  solarTermDefinitions.forEach((term) => {
    const dateKey = findSolarTermDateKey(year, term);
    if (!dateKey || Number(dateKey.slice(0, 4)) !== year) return;
    terms.set(dateKey, { name: term.name, note: term.note });
  });
  solarTermCache.set(year, terms);
  return terms;
}

function getGeneratedSolarTerm(dateKey) {
  return getSolarTermMap(Number(dateKey.slice(0, 4))).get(dateKey) || null;
}

function mergeCalendarFestivals(dateKey) {
  const byName = new Map();
  const addFestival = (festival) => {
    const current = byName.get(festival.name) || {
      name: festival.name,
      types: [],
      lunar: festival.lunar || "",
      isDayOff: false,
      isAdjustedWorkday: false,
    };
    current.types = [...new Set([...current.types, festival.type])];
    current.lunar = current.lunar || festival.lunar || "";
    current.isDayOff = current.isDayOff || Boolean(festival.isDayOff);
    current.isAdjustedWorkday = current.isAdjustedWorkday || Boolean(festival.isAdjustedWorkday);
    byName.set(festival.name, current);
  };

  [
    ...getFixedSolarFestivals(dateKey),
    ...getGeneratedLunarFestivals(dateKey),
    ...getGeneratedSolarTermFestivals(dateKey),
    ...getOfficialHolidayFestivals(dateKey),
  ].forEach(addFestival);

  return [...byName.values()];
}

function getCalendarDateData(dateKey, records = []) {
  const lunar = getLunarDateInfo(dateKey);
  const solarTerm = getGeneratedSolarTerm(dateKey);
  const festivals = mergeCalendarFestivals(dateKey);
  const hasSameSolarFestival = solarTerm && festivals.some((festival) => festival.name === solarTerm.name);

  return {
    date: dateKey,
    lunar,
    festivals,
    solarTerm,
    isDayOff: festivals.some((festival) => festival.isDayOff),
    isAdjustedWorkday: festivals.some((festival) => festival.isAdjustedWorkday),
    hasHoliday: festivals.length > 0,
    hasSolarTerm: Boolean(solarTerm),
    hasSameSolarFestival,
    records,
  };
}

function getCalendarDateSummary(dayData) {
  const lines = [];

  const eventLines = [];
  dayData.festivals.forEach((festival) => {
    const typeLabels = [];
    if (festival.types.includes("lunar-festival")) typeLabels.push("传统节日");
    if (festival.types.includes("fixed-festival")) typeLabels.push("节日");
    if (festival.types.includes("public-holiday")) typeLabels.push("法定节假日");
    if (festival.types.includes("adjusted-workday")) typeLabels.push("调休上班");
    eventLines.push(festival.name);
    if (festival.lunar) eventLines.push(festival.lunar);
    if (typeLabels.length) eventLines.push(typeLabels.join(" · "));
  });

  if (dayData.solarTerm && !dayData.hasSameSolarFestival) {
    eventLines.push(dayData.solarTerm.name);
    eventLines.push(dayData.solarTerm.note);
  } else if (dayData.solarTerm && dayData.hasSameSolarFestival) {
    eventLines.push("二十四节气");
  }

  if (dayData.isDayOff) eventLines.push("法定节假日");
  if (dayData.isAdjustedWorkday) eventLines.push("补班");

  if (eventLines.length) {
    lines.push(...[...new Set(eventLines)]);
  }

  if (dayData.records.length) {
    const typeCount = dayData.records.reduce((result, record) => {
      result[record.type] = (result[record.type] || 0) + 1;
      return result;
    }, {});
    if (lines.length) lines.push("");
    lines.push(`当天留下 ${dayData.records.length} 条记录`);
    Object.entries(typeCount).forEach(([type, count]) => {
      lines.push(`${type} × ${count}`);
    });
  }

  return lines.join("\n");
}

