function renderYearCalendar() {
  if (!yearCalendar || !calendarTitle || !calendarSummary) return;

  const recordMap = getCalendarRecordMap();
  const yearProgress = getYearProgress();
  const todayDate = getBeijingToday();
  const todayKey = `${todayDate.getFullYear()}-${String(todayDate.getMonth() + 1).padStart(2, "0")}-${String(todayDate.getDate()).padStart(2, "0")}`;
  const monthNames = ["一月", "二月", "三月", "四月", "五月", "六月", "七月", "八月", "九月", "十月", "十一月", "十二月"];
  const currentYear = todayDate.getFullYear();
  const currentMonth = todayDate.getMonth() + 1;
  const hiddenPastMonthCount = activeCalendarYear === currentYear ? currentMonth - 1 : 0;
  calendarTitle.textContent = activeCalendarYear;
  renderCalendarInfoToggles();
  renderCalendarPastMonthsToggle(hiddenPastMonthCount);
  const shouldAnimateProgress = calendarProgressAnimatedYear !== activeCalendarYear;
  calendarProgressAnimatedYear = activeCalendarYear;
  calendarSummary.innerHTML = `
    <div class="calendar-progress" title="截至今天&#10;今年已完整走过 ${yearProgress.elapsedDays} 天&#10;还剩 ${yearProgress.remainingDays} 天">
      <div>
        <span>今年已走过 ${yearProgress.elapsedDays} / ${yearProgress.totalDays} 天</span>
        <strong>${yearProgress.label}</strong>
      </div>
      <div class="calendar-progress-track" aria-label="年度进度 ${yearProgress.label}">
        <span class="${shouldAnimateProgress ? "" : "is-static"}" style="--year-progress: ${yearProgress.percent.toFixed(2)}%"></span>
      </div>
    </div>
  `;

  yearCalendar.innerHTML = monthNames
    .map((monthName, monthIndex) => ({ monthName, month: monthIndex + 1, monthIndex }))
    .filter(({ month }) => calendarPastMonthsOpen || activeCalendarYear !== currentYear || month >= currentMonth)
    .map(({ monthName, month, monthIndex }) => {
      const daysInMonth = new Date(activeCalendarYear, month, 0).getDate();
      const days = Array.from({ length: daysInMonth }, (_, index) => {
        const day = index + 1;
        const date = new Date(activeCalendarYear, monthIndex, day);
        const dateKey = formatCalendarDate(activeCalendarYear, month, day);
        const records = recordMap.get(dateKey) || [];
        const level = Math.min(records.length, 3);
        const dayData = getCalendarDateData(dateKey, records);
        const dayTitle = getCalendarDayTitle(dateKey, records);
        const hasEmojiBurst = getCalendarFestivalEmojis(dayData).length > 0;
        const hasCompletedFestival = isCalendarDayFestivalCompleted(dayData);
        const isPast = date < todayDate;
        const markerClass = calendarLunarNamesOpen
          ? ""
          : dayData.hasHoliday && dayData.hasSolarTerm
            ? "is-combo"
            : dayData.hasHoliday
              ? "is-holiday"
              : dayData.hasSolarTerm
                ? "is-solar-term"
                : "";
        const expandedNames = getCalendarExpandedNames(dayData);
        return `
          <button class="calendar-day ${isPast ? "is-past" : ""} ${date.getDay() === 0 ? "is-sunday" : ""} ${date.getDay() === 0 || date.getDay() === 6 ? "is-weekend" : ""} ${records.length ? `has-record level-${level}` : ""} ${hasEmojiBurst ? "has-calendar-surprise" : ""} ${hasCompletedFestival ? "is-festival-completed" : ""} ${dayData.hasHoliday ? "has-holiday" : ""} ${dayData.hasSolarTerm ? "has-solar-term" : ""} ${calendarLunarNamesOpen ? "is-lunar-mode" : ""} ${expandedNames.length ? "has-expanded-note" : ""} ${dayData.isDayOff ? "is-day-off" : ""} ${dayData.isAdjustedWorkday ? "is-adjusted-workday" : ""} ${dateKey === todayKey ? "is-today" : ""} ${dateKey === activeCalendarDate ? "is-selected" : ""}" type="button" data-calendar-date="${dateKey}" data-tooltip="${escapeHtml(dayTitle)}" aria-label="${dayTitle.replace(/\n/g, " ")}">
            <span>${getCalendarWeekday(date)}</span>
            <strong>${day}</strong>
            <i class="calendar-date-marks ${markerClass}" aria-hidden="true"></i>
            <em class="calendar-date-name">${expandedNames.map(escapeHtml).join(" / ")}</em>
          </button>
        `;
      });
      const activeRecords = recordMap.get(activeCalendarDate) || [];
      const activeDayData = getCalendarDateData(activeCalendarDate, activeRecords);
      const showDetail = activeCalendarDate.startsWith(`${activeCalendarYear}-${String(month).padStart(2, "0")}`);

      return `
        <section class="calendar-month">
          <h3>${monthName}</h3>
          <div class="calendar-days">${days.join("")}</div>
          ${showDetail ? renderCalendarDayDetail(activeDayData) : ""}
        </section>
      `;
    })
    .join("");

  const recordedDays = recordMap.size;
  const totalRecords = [...recordMap.values()].reduce((sum, records) => sum + records.length, 0);
  const hasOfficialHolidayArrangement = Boolean(officialHolidayArrangements[activeCalendarYear]);
  calendarSummary.insertAdjacentHTML(
    "beforeend",
    `
      <p>本年记录了 ${recordedDays} 天，总记录数 ${totalRecords} 条。</p>
      <p class="calendar-holiday-source">${hasOfficialHolidayArrangement ? "法定休假来源国务院办公厅节假日安排通知。" : "法定休假以已公布数据为准，未公布年份待更新。"}</p>
    `,
  );
}

