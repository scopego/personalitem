function getArchiveGroups(entries) {
  const years = new Map();

  entries.forEach((entry) => {
    const [year, month, day] = entry.date.split("-");
    if (!years.has(year)) {
      years.set(year, { year, count: 0, months: new Map() });
    }
    const yearGroup = years.get(year);
    yearGroup.count += 1;
    if (!yearGroup.months.has(month)) {
      yearGroup.months.set(month, { month, count: 0, days: new Map() });
    }
    const monthGroup = yearGroup.months.get(month);
    monthGroup.count += 1;
    if (!monthGroup.days.has(day)) {
      monthGroup.days.set(day, []);
    }
    monthGroup.days.get(day).push(entry);
  });

  return [...years.values()].map((yearGroup) => ({
    ...yearGroup,
    months: [...yearGroup.months.values()].map((monthGroup) => ({
      ...monthGroup,
      days: [...monthGroup.days.entries()].map(([day, dayEntries]) => ({ day, entries: dayEntries })),
    })),
  }));
}

