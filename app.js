document.addEventListener("keydown", (event) => {
  const lightbox = document.querySelector("#momentLightbox");
  if (lightbox) {
    if (event.key === "Escape") {
      event.preventDefault();
      closeMomentLightbox();
      return;
    }

    if (event.key === "ArrowLeft") {
      event.preventDefault();
      moveMomentLightbox(-1);
      return;
    }

    if (event.key === "ArrowRight") {
      event.preventDefault();
      moveMomentLightbox(1);
      return;
    }
  }

  const modal = document.querySelector("#mediaNoteModal");
  if (!modal || modal.hidden) return;

  if (event.key === "Escape") {
    event.preventDefault();
    closeMediaNoteModal();
    return;
  }

  if (event.key !== "Tab") return;

  const focusable = [
    ...modal.querySelectorAll(
      'button, input, textarea, select, a[href], [tabindex]:not([tabindex="-1"])',
    ),
  ].filter((element) => !element.disabled && !element.hidden);

  if (!focusable.length) return;

  const first = focusable[0];
  const last = focusable[focusable.length - 1];

  if (event.shiftKey && document.activeElement === first) {
    event.preventDefault();
    last.focus();
  } else if (!event.shiftKey && document.activeElement === last) {
    event.preventDefault();
    first.focus();
  }
});

document.addEventListener("submit", (event) => {
  const form = event.target.closest(".media-note-form");
  if (!form || !activeMediaNoteKey) return;

  event.preventDefault();
  const input = form.elements.note;
  const text = input.value.trim().slice(0, 30);
  if (!text) return;

  const notes = getMediaNotes();
  const currentNotes = Array.isArray(notes[activeMediaNoteKey]) ? notes[activeMediaNoteKey] : [];
  currentNotes.push({ text, name: "匿名" });
  notes[activeMediaNoteKey] = currentNotes;
  saveMediaNotes(notes);
  const returnKey = activeMediaNoteKey;
  closeMediaNoteModal({ returnFocus: false });
  renderMediaShelf();
  renderMoments();
  renderMomentAlbum();
  renderMomentView();
  window.setTimeout(() => {
    getMediaNoteButton(returnKey)?.focus();
  }, 190);
});

document.addEventListener("click", (event) => {
  const deleteButton = event.target.closest("[data-note-delete]");
  if (!deleteButton || !activeMediaNoteKey) return;

  event.preventDefault();
  const noteIndex = Number(deleteButton.dataset.noteDelete);
  if (!Number.isInteger(noteIndex)) return;

  const notes = getMediaNotes();
  const currentNotes = Array.isArray(notes[activeMediaNoteKey]) ? [...notes[activeMediaNoteKey]] : [];
  if (!currentNotes[noteIndex]) return;

  currentNotes.splice(noteIndex, 1);
  if (currentNotes.length) {
    notes[activeMediaNoteKey] = currentNotes;
  } else {
    delete notes[activeMediaNoteKey];
  }
  saveMediaNotes(notes);
  renderMediaShelf();
  renderMediaNoteModal();
});

